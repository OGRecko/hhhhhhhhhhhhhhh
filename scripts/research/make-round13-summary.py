#!/usr/bin/env python3
"""Writes RESEARCH-STATUS-ROUND13.md from the live data. No counts are typed by hand."""
import json, os, collections, glob

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
live = json.load(open(os.path.join(ROOT, 'src/data/speakers.json'), encoding='utf-8'))
status = json.load(open(os.path.join(HERE, 'queue-url-status.json'), encoding='utf-8'))
queue = json.load(open(os.path.join(HERE, 'provenance-queue.json'), encoding='utf-8'))
hist = json.load(open(os.path.join(HERE, 'round13-value-history.json'), encoding='utf-8'))
leads = json.load(open(os.path.join(HERE, 'directivity-leads.json'), encoding='utf-8'))
results = json.load(open(os.path.join(HERE, 'round13-url-results.json'), encoding='utf-8'))

archived = 0
for f in ['removed-unavailable-records.json', 'removed-owner-round5-records.json',
          'removed-owner-2026-10-12-decisions.json', 'removed-unavailable-2026-10-12.json']:
    archived += len(json.load(open(os.path.join(HERE, f), encoding='utf-8'))['records'])

fields = collections.Counter()
for r in live:
    for f in ('driverCount', 'active'):
        p = r.get(f + 'Provenance', {}) or {}
        fields[(f, p.get('status'), r.get(f) is None)] += 1
def cnt(f, st):
    return sum(v for (ff, s, _), v in fields.items() if ff == f and s == st)

url_status = collections.Counter(u['status'] for u in status['urls'])
outcomes = collections.Counter(fr['outcome'] for u in status['urls'] for fr in u.get('fieldResults', []))
r13_urls = [u for u in status['urls'] if u.get('round') == 13]
r13_outcomes = collections.Counter(fr['outcome'] for u in r13_urls for fr in u.get('fieldResults', []))
r13_promoted = [h for h in hist['entries'] if h.get('round') == 13]
dp = sum(1 for r in live if isinstance(r.get('frequencyResponse'), dict) and r['frequencyResponse'].get('points'))
lead_status = collections.Counter(l.get('status') for l in leads)
lead_r13 = [l['id'] for l in leads if l.get('round13Outcome')]

L = []
a = L.append
a('# Research status, round 13')
a('')
a('Generated by `scripts/research/make-round13-summary.py` from `src/data/speakers.json`, `scripts/research/queue-url-status.json`, `provenance-queue.json`, `round13-value-history.json`, `directivity-leads.json` and `round13-url-results.json`. Do not edit counts by hand.')
a('')
a('## Catalog')
a('')
a(f'- Live records: **{len(live)}**')
a(f'- Archived records: **{archived}** (archive files listed in `make-round13-summary.py`; no ID appears both live and archived)')
a(f'- Total reviewed: **{len(live) + archived}** (owner-approved 777 total; the older 774 baseline is not enumerated in the repo, see open items)')
a('')
a('## Structural provenance (driverCount / active)')
a('')
a('| Field | CITED_IN_NOTES_UNCHECKED | MANUFACTURER_VERIFIED | UNSOURCED (null) | MISSING (null) |')
a('|---|---:|---:|---:|---:|')
for f in ('driverCount', 'active'):
    a(f"| {f} | {cnt(f, 'CITED_IN_NOTES_UNCHECKED')} | {cnt(f, 'MANUFACTURER_VERIFIED')} | {cnt(f, 'UNSOURCED')} | {cnt(f, None)} |")
a('')
a(f"Unchecked populated fields (queue): **{queue['uncheckedItems']}**. Distinct source URLs with outstanding fields: **{queue['uniqueSourceUrls']}**. Fully resolved URLs: **{queue['resolvedSourceUrls'] if isinstance(queue['resolvedSourceUrls'], int) else len(queue['resolvedSourceUrls'])}**.")
a('')
a('## URL queue (queue-url-status/v2)')
a('')
a(f"- Status file URLs: **{len(status['urls'])}**")
for k in sorted(url_status):
    a(f'- {k}: **{url_status[k]}**')
a(f'- URLs opened in round 13: **{len(r13_urls)}** (entries in `round13-url-results.json`)')
a('- Field outcomes across all recorded URLs: ' + ', '.join(f'{k} {v}' for k, v in sorted(outcomes.items())))
a('- Field outcomes recorded in round 13: ' + (', '.join(f'{k} {v}' for k, v in sorted(r13_outcomes.items())) or 'none'))
a(f'- Field values promoted to MANUFACTURER_VERIFIED in round 13: **{len(r13_promoted)}**')
a('')
a('## Other inventories')
a('')
a(f'- Live records carrying `frequencyResponse.points` (response datasets with points): **{dp}** (the round brief cites 25; the reconciliation is an open item).')
a(f'- Directivity leads: **{len(leads)}**; status: ' + ', '.join(f'{k} {v}' for k, v in sorted(lead_status.items(), key=lambda x: str(x[0]))))
a(f'- Directivity leads with a round-13 outcome recorded: **{len(lead_r13)}** ({", ".join(lead_r13) or "none"})')
a('')
a('## Round 13 changes')
a('')
a('- Opened and recorded per URL in `round13-url-results.json`; promotions applied by `apply-round13-queue-batch.py` only where the source is the manufacturer host and the stored value matches.')
a('- Non-manufacturer hosts (HEDD manual on arispro.ru) are recorded as SUPPORTED_NOT_PROMOTED. The distributor-copy policy is still an owner decision.')
a('- Genelec 8331A SOFA: sandbox egress to zenodo.org is blocked (TLS failure, host not on the allow-list). MD5 not checked; not imported.')
a('')
a('## Open items (not completed in round 13)')
a('')
a(f"- {url_status.get('OPEN', 0)} source URLs in the status file are still OPEN (never opened). Queue-level outstanding URLs: {queue['uniqueSourceUrls']} (includes checked URLs with fields still outstanding). See `PROVENANCE-QUEUE.md`.")
a('- Bose S1 Pro driverCount: NOT_EXTRACTED from chunk 0; parts-list chunks still to open.')
a('- Distributor/aggregator copies: owner policy decision required before any promotion.')
a('- Response datasets, directivity leads (except Genelec status), 227 withdrawn and 70 restored values, ELX200-15 row reconciliation, LSR32, NS-6490, Turbosound iP15B, QSC WL3082/WL212-sw: not completed this round.')
a('- Catalog 774-to-777: owner-approved 777 total reconciles to 659 + 118 with no duplicate IDs; the 774 baseline list is not in the repo, so the +3 cannot be traced item by item.')
a('')
open(os.path.join(HERE, 'RESEARCH-STATUS-ROUND13.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('wrote RESEARCH-STATUS-ROUND13.md')

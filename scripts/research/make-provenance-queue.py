#!/usr/bin/env python3
"""Generate the field-provenance work queue from src/data/speakers.json.

A queue item is a populated driverCount or active value whose provenance is still CITED_IN_NOTES_UNCHECKED, i.e. the
value is attached to a URL from the record notes that has not been opened and checked against that field.
Items are grouped by source URL so one opened page can settle every item that cites it.
Writes PROVENANCE-QUEUE.md and provenance-queue.json. Counts are computed here, never typed by hand.
"""
import json, os, collections
from urllib.parse import urlparse

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
DATA = os.path.join(ROOT, 'src', 'data', 'speakers.json')
OUT_JSON = os.path.join(ROOT, 'scripts', 'research', 'provenance-queue.json')
OUT_MD = os.path.join(ROOT, 'scripts', 'research', 'PROVENANCE-QUEUE.md')


def main():
    db = json.load(open(DATA, encoding='utf-8'))
    status_counts = collections.Counter()
    items = []
    for r in db:
        for f in ('driverCount', 'active'):
            p = r.get(f + 'Provenance') or {}
            st = p.get('status', 'MISSING')
            status_counts[(f, st, 'null' if r.get(f) is None else 'value')] += 1
            if st == 'CITED_IN_NOTES_UNCHECKED':
                items.append({'id': r['id'], 'field': f, 'value': r.get(f), 'source': p.get('source')})
    by_url = collections.defaultdict(list)
    for it in items:
        by_url[it['source']].append(it)
    groups = sorted(by_url.items(), key=lambda kv: (-len(kv[1]), kv[0] or ''))
    queue = {
        'generated_from': 'src/data/speakers.json',
        'liveRecords': len(db),
        'uncheckedItems': len(items),
        'uniqueSourceUrls': len(by_url),
        'statusCounts': [{'field': f, 'status': s, 'value': v, 'count': c} for (f, s, v), c in sorted(status_counts.items())],
        'groups': [{'url': u, 'host': urlparse(u or '').netloc, 'items': len(v),
                    'records': sorted({x['id'] for x in v}), 'fields': sorted({x['field'] for x in v})} for u, v in groups],
    }
    with open(OUT_JSON, 'w', encoding='utf-8') as fh:
        json.dump(queue, fh, indent=2, ensure_ascii=False); fh.write('\n')
    lines = [
        '# Field provenance queue',
        '',
        'Generated by `scripts/research/make-provenance-queue.py` from `src/data/speakers.json`. Do not edit by hand.',
        '',
        f'- Live records: **{len(db)}**',
        f'- Populated driverCount/active values still `CITED_IN_NOTES_UNCHECKED`: **{len(items)}**',
        f'- Distinct source URLs to open: **{len(by_url)}**',
        '',
        'A value leaves this queue only when its URL has been opened and the exact field is quoted in',
        '`provenance-ledger-*.json`. Values that the page does not state stay here or are set to null.',
        '',
        '| # | Items | Host | Source URL |',
        '|---:|---:|---|---|',
    ]
    for i, (u, v) in enumerate(groups, 1):
        lines.append(f'| {i} | {len(v)} | {urlparse(u or "").netloc} | {u} |')
    with open(OUT_MD, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines) + '\n')
    print(f"records={len(db)} unchecked_items={len(items)} unique_urls={len(by_url)}")


if __name__ == '__main__':
    main()
